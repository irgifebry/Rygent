#!/bin/bash
set -e
if [[ $EUID -ne 0 ]]; then echo "Error: Run as root (sudo)"; exit 1; fi
echo ">> Extracting Rygent Agent..."
PAYLOAD_LINE=$(( $(grep -an "^# __START_OF_BASE64__" "$0" | head -n 1 | cut -d: -f1) + 1 ))
tail -n +$PAYLOAD_LINE "$0" | base64 -d > /tmp/rygent.tar.gz
INSTALL_DIR="/opt/rygent-agent"
rm -rf "$INSTALL_DIR" && mkdir -p "$INSTALL_DIR"
tar -xzf /tmp/rygent.tar.gz -C "$INSTALL_DIR" && rm /tmp/rygent.tar.gz
echo ">> Setting up dependencies..."
OS="debian"; [[ -f /etc/redhat-release ]] && OS="redhat"; [[ -f /etc/arch-release ]] && OS="arch"
case $OS in
  debian) apt-get update -qq && apt-get install -y python3-tk python3-pil.imagetk python3-pip curl >/dev/null ;;
  redhat) dnf install -y python3-tkinter python3-pillow-tk python3-pip curl >/dev/null ;;
  arch) pacman -Sy --noconfirm python3 tk export-pillow python-pip curl >/dev/null ;;
esac
pip3 install flask flask-cors psutil python-dotenv zeroconf distro pystray Pillow qrcode speedtest-cli --break-system-packages 2>/dev/null || pip3 install flask flask-cors psutil python-dotenv zeroconf distro pystray Pillow qrcode speedtest-cli 2>/dev/null
ARCH=$(uname -m)
case $ARCH in
  x86_64) URL="https://github.com/cloudflare/cloudflared/releases/latest/download/cloudflared-linux-amd64" ;;
  aarch64) URL="https://github.com/cloudflare/cloudflared/releases/latest/download/cloudflared-linux-arm64" ;;
  armv7l|armv6l) URL="https://github.com/cloudflare/cloudflared/releases/latest/download/cloudflared-linux-arm" ;;
esac
[[ -n "$URL" ]] && echo ">> Fetching cloudflared for $ARCH..." && curl -L -o "$INSTALL_DIR/cloudflared" "$URL" && chmod +x "$INSTALL_DIR/cloudflared"
cat <<'L_EOF' > /usr/bin/rygent-agent
#!/bin/bash
cd /opt/rygent-agent
[[ ! -f ~/.rygent/.env ]] && mkdir -p ~/.rygent && cp .env.default ~/.rygent/.env 2>/dev/null
export DISPLAY=:0; unset WAYLAND_DISPLAY; python3 agent_gui.py "$@"
L_EOF
chmod 755 /usr/bin/rygent-agent
[[ -f "$INSTALL_DIR/.env.example" ]] && cp "$INSTALL_DIR/.env.example" "$INSTALL_DIR/.env.default"
mkdir -p /usr/share/applications /usr/share/icons/hicolor/512x512/apps
cp "$INSTALL_DIR/icon.png" /usr/share/icons/hicolor/512x512/apps/rygent-agent.png 2>/dev/null || true
cat <<'D_EOF' > /usr/share/applications/rygent-agent.desktop
[Desktop Entry]
Version=1.0
Type=Application
Name=Rygent Agent
GenericName=System Monitor
Comment=Monitor your system resources remotely
Exec=/usr/bin/rygent-agent
Icon=rygent-agent
Terminal=false
Categories=System;Utility;Monitor;
Keywords=system;monitor;remote;rygent;
StartupNotify=true
StartupWMClass=agent_gui
D_EOF
chmod 644 /usr/share/applications/rygent-agent.desktop
gtk-update-icon-cache -f /usr/share/icons/hicolor || true
update-desktop-database -q /usr/share/applications || true
echo ">> Success! Run 'rygent-agent' to start."
exit 0
